/**
 * Derin Analiz kartı.
 *  kind: 'xray' | 'ik'
 *  assessmentId: İK için aday değerlendirmesi
 *  buildData(): () => ({ data, sources })  — Claude'a gidecek toplu veri (kişisel veri içermez)
 */
export function deepCard({ kind, assessmentId = null, buildData, intro }) {
  const id = 'deep-' + kind;
  const ph = html`<div class="card deep-card" id="${id}"><div class="dim" style="padding:8px 0">${t('Derin Analiz yükleniyor…', 'Loading Deep Analysis…')}</div></div>`;
  const mount = async (root) => {
    const box = $('#' + id, root);
    if (!box) return;
    let usage, list = [];
    try {
      [usage, list] = await Promise.all([api.aiUsage(state.org.id), api.listDeepAnalyses(state.org.id, { kind, assessmentId })]);
    } catch (e) {
      box.innerHTML = toStr(html`<p class="dim">${errText(e)}</p>`);
      return;
    }
    const used = kind === 'xray' ? usage.xray_used : usage.ik_used;
    const limit = kind === 'xray' ? usage.xray_limit : usage.ik_limit;
    const left = Math.max(0, limit - used);
    const title = kind === 'xray' ? t('Claude ile Derin Analiz', 'Deep Analysis with Claude') : t('Claude ile Derin Analiz ve Mülakat Rehberi', 'Deep Analysis & Interview Guide with Claude');
    const desc = intro || (kind === 'xray'
      ? t('Claude, tüm panellerinizin sonuçlarını birlikte okuyup bir iş danışmanı gibi yorumlar: genel durum, alanlar arası bağlantılar, olası kök nedenler, öncelikli hamleler, 30-60-90 günlük yol haritası ve takip edilecek göstergeler — bilimsel kaynaklara dayanarak.',
        'Claude reads all your panels together and interprets them like a business advisor: overall picture, cross-panel links, likely root causes, priority moves, a 30-60-90 day roadmap and indicators to track — grounded in scientific sources.')
      : t('Claude, adayın bilişsel, durumsal yargı, kişilik ve dürüstlük sonuçlarını birlikte yorumlar; güçlü yönleri, doğrulanması gereken noktaları ve pozisyona uyumu açıklar, bu adaya özel mülakat soruları (iyi cevap / dikkat işareti ile) ve ilk 90 gün önerileri hazırlar.',
        'Claude interprets the candidate\'s cognitive, judgement, personality and honesty results together; explains strengths, points to verify and role fit, and prepares candidate-specific interview questions (with strong-answer / warning-sign cues) and first-90-day advice.'));
    const lockBtn = html`<a class="btn primary" href="#/subscribe">${raw(icon('lock'))} ${t('Abonelikle aç', 'Unlock with subscription')}</a>`;
    const runBtn = html`<button class="btn primary" id="${id}-run" ${left ? '' : 'disabled'}>${raw(icon('spark'))} ${list.length ? t('Yeni analiz oluştur', 'Create new analysis') : t('Analizi oluştur', 'Create analysis')}</button>`;
    box.innerHTML = toStr(html`
      <div class="deep-head">
        <div><div class="eyebrow">${t('Yapay zekâ destekli', 'AI-powered')}</div><h3>${raw(icon('spark'))} ${title}</h3><p class="muted" style="margin:6px 0 0">${desc}</p></div>
        <div class="deep-cta">${!usage.paid ? lockBtn : canWrite() ? runBtn : ''}
          ${usage.paid ? html`<small class="dim">${t(`Bu ay ${used}/${limit} kullanıldı · ${fmtDate(usage.renews_at, getLang())} yenilenir`, `${used}/${limit} used this month · renews ${fmtDate(usage.renews_at, getLang())}`)}</small>` : ''}</div>
      </div>
      ${!usage.paid ? html`<div class="deep-lock">${raw(icon('lock'))}<div><b>${t('Derin Analiz ücretli abonelikte açılır', 'Deep Analysis is included in the paid subscription')}</b>
        <p>${t('Deneme süresinde Kurum Röntgeni ve tüm raporlar açıktır; Claude ile Derin Analiz, ProX Yedilisi aboneliğiyle kullanılır.', 'During the trial the reports are open; Deep Analysis with Claude comes with the ProX Seven subscription.')}</p></div></div>` : ''}
      ${usage.paid && !left ? html`<div class="alert warn" style="margin-top:12px">${t('Bu ayki analiz hakkınız doldu. Kayıtlı analizlerinizi aşağıdan görüntüleyebilirsiniz.', 'This month\'s quota is used up. You can still view your saved analyses below.')}</div>` : ''}
      <div id="${id}-out">${list[0] ? analysisView(list[0]) : ''}</div>
      ${list.length > 1 ? html`<details class="deep-hist"><summary>${t('Önceki analizler', 'Earlier analyses')} (${list.length - 1})</summary>
        <div class="list" style="margin-top:10px">${list.slice(1).map((a) => html`<div class="li"><span>${fmtDate(a.created_at, getLang())}</span><button class="btn sm" data-open="${a.id}">${t('Görüntüle', 'View')}</button></div>`)}</div></details>` : ''}`);
    const bindPrint = () => $$('[data-print]', box).forEach((b) => (b.onclick = () => {
      document.body.classList.add('print-deep');
      printPage(title).finally(() => document.body.classList.remove('print-deep'));
    }));
    bindPrint();
    $$('[data-open]', box).forEach((b) => (b.onclick = () => {
      const a = list.find((x) => x.id === b.dataset.open);
      $('#' + id + '-out', box).innerHTML = toStr(analysisView(a));
      bindPrint();
      $('#' + id + '-out', box).scrollIntoView({ behavior: 'smooth', block: 'start' });
    }));
    const run = $('#' + id + '-run', box);
    if (!run) return;
    run.onclick = async () => {
      if (!usage.consent && !(await consentSheet(kind))) return;
      usage.consent = true;
      const okRun = await new Promise((res) => {
        const s = sheet(html`<h3>${title}</h3>
          <p class="muted">${t(`Bu işlem bu ayki hakkınızdan 1 adet kullanır (kalan: ${left}). Claude analizi genellikle 30–90 saniyede hazırlar. Analiz başarısız olursa hakkınız harcanmaz.`, `This uses 1 of this month's quota (left: ${left}). Claude usually takes 30–90 seconds. If it fails, no quota is used.`)}</p>
          <div class="row end"><button class="btn" id="rq-no">${t('Vazgeç', 'Cancel')}</button><button class="btn primary" id="rq-go">${raw(icon('spark'))} ${t('Başlat', 'Start')}</button></div>`, { onClose: () => res(false) });
        s.el.querySelector('#rq-no').onclick = () => s.close();
        s.el.querySelector('#rq-go').onclick = () => { s.el.closest('.sheet-bg').remove(); res(true); };
      });
      if (!okRun) return;
      let payload;
      try {
        payload = await buildData();
      } catch (e) {
        return toast(errText(e), 'err');
      }
      const out = $('#' + id + '-out', box);
      out.innerHTML = toStr(html`<div class="deep-wait"><span class="spin"></span><div><b>${t('Claude analiz ediyor…', 'Claude is analysing…')}</b><p class="dim">${t('Bu işlem 1–2 dakika sürebilir. Sayfadan ayrılmayın.', 'This can take 1–2 minutes. Please stay on this page.')}</p></div></div>`);
      setBusy(run, true);
      try {
        await api.runDeepAnalysis({ org: state.org.id, kind, assessment_id: assessmentId, lang: getLang(), data: payload.data, sources: payload.sources });
        toast(t('Derin Analiz hazır.', 'Deep Analysis is ready.'), 'ok');
        mount(root);
      } catch (e) {
        setBusy(run, false);
        out.innerHTML = toStr(html`<div class="alert err">${errText(e)}</div>`);
      }
    };
  };
  return { html: ph, mount };
}
