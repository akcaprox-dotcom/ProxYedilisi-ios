// ------------------------------------------------------------ Güvenli, küçük Markdown çevirici
// Önce tüm metin kaçışlanır; ardından yalnızca başlık, kalın, italik, liste, paragraf ve [n] atıfları biçimlenir.
export function markdown(md) {
  const lines = esc(String(md || '').replace(/\r/g, '')).split('\n');
  const inline = (s) => s
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/(^|[\s(])\*(?!\s)(.+?)\*(?=[\s).,;:!?]|$)/g, '$1<i>$2</i>')
    .replace(/\[(\d{1,2}(?:\s*[,–-]\s*\d{1,2})*)\]/g, '<sup class="cite">[$1]</sup>');
  let out = '', list = null, para = [];
  const flushP = () => { if (para.length) { out += `<p>${inline(para.join(' '))}</p>`; para = []; } };
  // Numaralı listede ilk numara korunur (araya madde işaretli satırlar girse de 1, 2, 3 diye devam eder)
  const flushL = () => { if (list) { out += `<${list.t}${list.t === 'ol' && list.start > 1 ? ` start="${list.start}"` : ''}>${list.items.map((i) => `<li>${inline(i)}</li>`).join('')}</${list.t}>`; list = null; } };
  for (const raw0 of lines) {
    const l = raw0.trimEnd();
    let m;
    if (!l.trim()) { flushP(); flushL(); continue; }
    if ((m = /^(#{1,4})\s+(.*)$/.exec(l))) {
      flushP(); flushL();
      const lv = Math.min(4, m[1].length + 1);
      out += `<h${lv}>${inline(m[2])}</h${lv}>`;
      continue;
    }
    if ((m = /^\s*[-*•]\s+(.*)$/.exec(l))) {
      flushP();
      if (!list || list.t !== 'ul') { flushL(); list = { t: 'ul', items: [] }; }
      list.items.push(m[1]);
      continue;
    }
    if ((m = /^\s*(\d+)[.)]\s+(.*)$/.exec(l)) && !/^\[\d/.test(l.trim())) {
      flushP();
      if (!list || list.t !== 'ol') { flushL(); list = { t: 'ol', items: [], start: +m[1] }; }
      list.items.push(m[2]);
      continue;
    }
    if (/^\[\d+\]/.test(l.trim())) { flushP(); flushL(); out += `<p class="ref">${l.trim()}</p>`; continue; }
    flushL();
    para.push(l.trim());
  }
  flushP(); flushL();
  return out;
}

